/**
 * Build the shipped artifact: the single Host bundle `lib/index.js`.
 *
 * Build rules:
 *   - the Host bundle is NOT minified and keeps names, so stack traces and
 *     plugin logs stay readable;
 *   - `@deepseek-ai/*` specifiers stay external: the Harness resolves them
 *     from its own installation.
 *
 * @module dsh-design-symposium/scripts/build
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Host externals: the Harness supplies these. */
export const HOST_EXTERNAL = ['@deepseek-ai/*'];

const HOST_BANNER = `/**
 * dsh-design-symposium — Host half (generated by scripts/build.mjs from src/).
 * Do not edit: edit src/ instead.
 */`;

const CLIENT_BANNER = `/**
 * dsh-design-symposium — client half (generated by scripts/build.mjs from src/).
 * Factory-CJS registration for the kernel module Loader; do not edit.
 * A plain ESM build here kills the whole GUI at parse time (2026-10-28).
 */`;

/**
 * Bundle the single Host artifact.
 * @param options - `esbuild` is injected so callers control module resolution.
 * @returns the written output paths.
 */
export async function build(options = {}) {
  let esbuild = options.esbuild;
  if (esbuild === undefined) {
    esbuild = await import('esbuild').catch(() => undefined);
  }
  if (esbuild === undefined) {
    throw new Error('esbuild 未安装：请先运行 pnpm install（或 npm install esbuild）。');
  }
  const logLevel = options.logLevel ?? 'info';
  mkdirSync(resolve(root, 'lib'), { recursive: true });

  const host = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['src/index.ts'],
    outfile: 'lib/index.js',
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    external: HOST_EXTERNAL,
    // Keep readable names in the shipped bundle for log/stack readability.
    minify: false,
    keepNames: true,
    sourcemap: false,
    banner: { js: HOST_BANNER },
    logLevel,
  });


  // Client half. The kernel Loader loads plugin bundles as ordinary
  // <script> tags, so the shipped file must be a factory-CJS registration —
  // esbuild emits the CJS body (`module.exports = ...`) and we wrap it into
  // `window.__ModuleLoader__.load({ id, factory })` by hand. Bare `require`
  // calls (react) survive bundling and resolve through the Loader at render
  // time. Never switch this to format:'esm': a top-level `export` fails the
  // script at parse time and the GUI never boots (2026-10-28 crash).
  const clientBody = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['src/client.ts'],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    write: false,
    // Keep readable names in the shipped bundle for devtools readability.
    minify: false,
    keepNames: true,
    logLevel,
  });
  const clientSource = [
    CLIENT_BANNER,
    'window.__ModuleLoader__.load({',
    '  id: "dsh-design-symposium",',
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    clientBody.outputFiles[0].text.trimEnd(),
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');
  // Guard the contract at build time: if esbuild ever emits ESM here, fail
  // the build instead of shipping a renderer-killer.
  if (/^\s*(export|import)\s/m.test(clientSource.replace(CLIENT_BANNER, ''))) {
    throw new Error('lib/client.js 产物含顶层 export/import：Loader 只接受 factory-CJS，构建中止。');
  }
  writeFileSync(resolve(root, 'lib/client.js'), clientSource, 'utf8');

  return {
    host,
    client: clientBody,
    outfiles: [resolve(root, 'lib/index.js'), resolve(root, 'lib/client.js')],
  };
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const { outfiles } = await build();
  for (const path of outfiles) console.log(`[build] 已生成 ${path}`);
}
